// Generates src/lintRules.generated.js: every bpmnlint rule/config the studio uses, imported
// statically, so the linter runs in the browser (and in Node) without resolving files at runtime.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const recommended = require('bpmnlint/config/recommended');
const compat = require('bpmnlint-plugin-camunda-compat');

const coreNames = Object.keys(recommended.rules).sort();
// the plugin's "rules" map holds paths for Node's resolver, not functions
const compatRules = Object.entries(compat.rules).sort(([a], [b]) => a.localeCompare(b));

const id = (prefix, name) => prefix + name.replace(/[^a-z0-9]/gi, '_');

// "./rules/x" = a file or folder of the plugin; "bpmnlint/x" = a core bpmnlint rule the plugin re-uses.
// Resolved to the real file now, so the generated imports need no resolution magic later.
const NM = '/node_modules/';
function specifier(spec) {
  const file = require.resolve(spec).split('\\').join('/');
  return file.slice(file.lastIndexOf(NM) + NM.length);
}
function compatSpecifier(path) {
  if (path.startsWith('./')) return specifier(`bpmnlint-plugin-camunda-compat/${path.slice(2)}`);
  if (path.startsWith('bpmnlint/')) return specifier(`bpmnlint/rules/${path.slice('bpmnlint/'.length)}`);
  throw new Error(`unexpected rule path ${path}`);
}

const out = [
  '// GENERATED by scripts/gen-lint-rules.mjs — do not edit.',
  `import recommended from '${specifier('bpmnlint/config/recommended')}';`,
  "import compat from 'bpmnlint-plugin-camunda-compat';",
  ...coreNames.map(n => `import ${id('r_', n)} from '${specifier(`bpmnlint/rules/${n}`)}';`),
  ...compatRules.map(([n, path]) => `import ${id('c_', n)} from '${compatSpecifier(path)}';`),
  '',
  '/** Cache for bpmnlint\'s StaticResolver: "rule:<pkg>/<name>" and "config:<pkg>/<name>". */',
  'export const LINT_CACHE = {',
  "  'config:bpmnlint/recommended': recommended,",
  ...coreNames.map(n => `  'rule:bpmnlint/${n}': ${id('r_', n)},`),
  ...compatRules.map(([n]) => `  'rule:bpmnlint-plugin-camunda-compat/${n}': ${id('c_', n)},`),
  '};',
  'for (const [name, cfg] of Object.entries(compat.configs)) LINT_CACHE[`config:bpmnlint-plugin-camunda-compat/${name}`] = cfg;',
  '',
  'export const COMPAT_CONFIGS = Object.keys(compat.configs);',
  ''
].join('\n');

writeFileSync(new URL('../src/lintRules.generated.js', import.meta.url), out);
console.log(`src/lintRules.generated.js: ${coreNames.length} bpmnlint rules + ${compatRules.length} camunda-compat rules`);
